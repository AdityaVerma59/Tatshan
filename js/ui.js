export function svgFromString(str) {
  // Only ever called with SVG generated by our own qr.js.
  const doc = new DOMParser().parseFromString(str, 'image/svg+xml');
  return document.importNode(doc.documentElement, true);
}

// ---- toast ----
export function toast(message, { kind = '' } = {}) {
  let box = document.getElementById('toasts');
  if (!box) { box = h('div', { id: 'toasts', 'aria-live': 'polite' }); document.body.append(box); }
  const t = h('div', { class: `toast ${kind}` }, message);
  box.append(t);
  setTimeout(() => { t.classList.add('out'); setTimeout(() => t.remove(), 300); }, 4200);
}

// ---- modal / bottom sheet ----
export function openSheet({ title, subtitle, body, wide = false, onClose } = {}) {
  const previous = document.activeElement;
  const close = () => {
    document.removeEventListener('keydown', onKey);
    overlay.classList.add('out');
    setTimeout(() => overlay.remove(), 180);
    if (!document.querySelector('.overlay:not(.out)')) document.documentElement.classList.remove('lock');
    if (onClose) onClose();
    if (previous && previous.focus) previous.focus();
  };
  const onKey = (e) => { if (e.key === 'Escape') { e.stopPropagation(); close(); } };
  const sheet = h('div', { class: `sheet ${wide ? 'wide' : ''}`, role: 'dialog', 'aria-modal': 'true', 'aria-label': title || 'Dialog', tabindex: '-1' },
    h('div', { class: 'sheet-head' },
      h('div', {}, title && h('h2', { class: 'sheet-title' }, title), subtitle && h('p', { class: 'sheet-sub' }, subtitle)),
      h('button', { class: 'icon-btn', 'aria-label': 'Close', onClick: close }, icon('x'))),
    body);
  const overlay = h('div', { class: 'overlay', onClick: (e) => { if (e.target === overlay) close(); } }, sheet);
  document.body.append(overlay);
  document.documentElement.classList.add('lock');
  document.addEventListener('keydown', onKey);
  sheet.focus();
  return { close, el: sheet };
}

